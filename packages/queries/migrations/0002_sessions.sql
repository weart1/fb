-- One row per session (after merges). Fed by a materialized view on `events`.
-- This is the main pre-aggregation: overview, campaigns, explorer and every report filter
-- (campaign, ad set, ad, creative, source, device, browser, country) run against it.
CREATE TABLE IF NOT EXISTS sessions
(
  project_id        LowCardinality(String),
  session_date      Date,
  session_id        UUID,
  anonymous_id      SimpleAggregateFunction(any, UUID),
  user_id           SimpleAggregateFunction(max, String),
  start             SimpleAggregateFunction(min, DateTime64(3, 'UTC')),
  end               SimpleAggregateFunction(max, DateTime64(3, 'UTC')),
  events            SimpleAggregateFunction(sum, UInt64),
  pageviews         SimpleAggregateFunction(sum, UInt64),
  interactions      SimpleAggregateFunction(sum, UInt64),
  active_ms         SimpleAggregateFunction(sum, UInt64),
  entry_path        AggregateFunction(argMin, String, DateTime64(3, 'UTC')),
  exit_path         AggregateFunction(argMax, String, DateTime64(3, 'UTC')),

  channel           SimpleAggregateFunction(any, LowCardinality(String)),
  ad_platform       SimpleAggregateFunction(any, LowCardinality(String)),
  utm_source        SimpleAggregateFunction(any, LowCardinality(String)),
  utm_medium        SimpleAggregateFunction(any, LowCardinality(String)),
  utm_campaign      SimpleAggregateFunction(any, String),
  utm_content       SimpleAggregateFunction(any, String),
  utm_term          SimpleAggregateFunction(any, String),
  campaign_id       SimpleAggregateFunction(any, String),
  adset_id          SimpleAggregateFunction(any, String),
  ad_id             SimpleAggregateFunction(any, String),
  creative_id       SimpleAggregateFunction(any, String),
  click_id_type     SimpleAggregateFunction(any, LowCardinality(String)),
  referrer_domain   SimpleAggregateFunction(any, LowCardinality(String)),
  landing_path      SimpleAggregateFunction(any, String),

  ft_channel        SimpleAggregateFunction(any, LowCardinality(String)),
  ft_ad_platform    SimpleAggregateFunction(any, LowCardinality(String)),
  ft_utm_source     SimpleAggregateFunction(any, LowCardinality(String)),
  ft_utm_campaign   SimpleAggregateFunction(any, String),
  ft_campaign_id    SimpleAggregateFunction(any, String),
  ft_adset_id       SimpleAggregateFunction(any, String),
  ft_ad_id          SimpleAggregateFunction(any, String),
  ft_creative_id    SimpleAggregateFunction(any, String),
  ft_ts             SimpleAggregateFunction(min, DateTime64(3, 'UTC')),

  device_type       SimpleAggregateFunction(any, LowCardinality(String)),
  browser           SimpleAggregateFunction(any, LowCardinality(String)),
  os                SimpleAggregateFunction(any, LowCardinality(String)),
  in_app_browser    SimpleAggregateFunction(any, LowCardinality(String)),
  country           SimpleAggregateFunction(any, LowCardinality(String)),
  city              SimpleAggregateFunction(any, String),
  viewport_w        SimpleAggregateFunction(any, UInt16),

  flow_started      SimpleAggregateFunction(max, UInt8),
  flow_completed    SimpleAggregateFunction(max, UInt8),
  max_step          SimpleAggregateFunction(max, UInt8),
  signed_up         SimpleAggregateFunction(max, UInt8),
  purchases         SimpleAggregateFunction(sum, UInt64),
  revenue           SimpleAggregateFunction(sum, Float64),
  errors            SimpleAggregateFunction(sum, UInt64),
  rage_clicks       SimpleAggregateFunction(sum, UInt64),
  dead_clicks       SimpleAggregateFunction(sum, UInt64),
  field_errors      SimpleAggregateFunction(sum, UInt64),
  step_backs        SimpleAggregateFunction(sum, UInt64),
  has_replay        SimpleAggregateFunction(max, UInt8),
  experiments       SimpleAggregateFunction(any, Map(String, String))
)
ENGINE = AggregatingMergeTree
PARTITION BY toYYYYMM(session_date)
ORDER BY (project_id, session_date, session_id)
TTL session_date + INTERVAL 395 DAY;

CREATE MATERIALIZED VIEW IF NOT EXISTS sessions_mv TO sessions AS
SELECT
  project_id,
  toDate(session_start) AS session_date,
  session_id,
  any(anonymous_id) AS anonymous_id,
  max(user_id) AS user_id,
  min(ts) AS start,
  max(ts) AS end,
  count() AS events,
  countIf(event = '$pageview') AS pageviews,
  countIf(event IN ('$click', '$form_field_focus', '$scroll_depth', 'onboarding_step_completed')) AS interactions,
  sumIf(duration_ms, event = '$pageleave') AS active_ms,
  argMinState(path, ts) AS entry_path,
  argMaxState(path, ts) AS exit_path,
  any(channel) AS channel,
  any(ad_platform) AS ad_platform,
  any(utm_source) AS utm_source,
  any(utm_medium) AS utm_medium,
  any(utm_campaign) AS utm_campaign,
  any(utm_content) AS utm_content,
  any(utm_term) AS utm_term,
  any(campaign_id) AS campaign_id,
  any(adset_id) AS adset_id,
  any(ad_id) AS ad_id,
  any(creative_id) AS creative_id,
  any(click_id_type) AS click_id_type,
  any(referrer_domain) AS referrer_domain,
  any(landing_path) AS landing_path,
  any(ft_channel) AS ft_channel,
  any(ft_ad_platform) AS ft_ad_platform,
  any(ft_utm_source) AS ft_utm_source,
  any(ft_utm_campaign) AS ft_utm_campaign,
  any(ft_campaign_id) AS ft_campaign_id,
  any(ft_adset_id) AS ft_adset_id,
  any(ft_ad_id) AS ft_ad_id,
  any(ft_creative_id) AS ft_creative_id,
  min(ft_ts) AS ft_ts,
  any(device_type) AS device_type,
  any(browser) AS browser,
  any(os) AS os,
  any(in_app_browser) AS in_app_browser,
  any(country) AS country,
  any(city) AS city,
  any(viewport_w) AS viewport_w,
  maxIf(1, event = 'onboarding_started') AS flow_started,
  maxIf(1, event = 'onboarding_completed') AS flow_completed,
  max(step) AS max_step,
  maxIf(1, event = 'sign_up') AS signed_up,
  countIf(event = 'purchase') AS purchases,
  sumIf(revenue, event IN ('purchase', '$revenue')) AS revenue,
  countIf(event = '$error') AS errors,
  countIf(event = '$rage_click') AS rage_clicks,
  countIf(event = '$dead_click') AS dead_clicks,
  countIf(event IN ('$form_field_error', 'onboarding_step_error')) AS field_errors,
  countIf(event = 'onboarding_step_back') AS step_backs,
  max(has_replay) AS has_replay,
  any(experiments) AS experiments
FROM events
GROUP BY project_id, session_date, session_id;
